#!/usr/bin/env bash
# Builds sbx-native.c into a static, libc-free x86_64 ELF and regenerates
# bench/src/fairness/native-binary.ts (base64 + SHA-256). Baseline x86-64 only: no provider gets
# a faster code path from wider vectors. Run from anywhere: bash bench/native/build.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "${work:?}"' EXIT
gcc -std=c11 -O2 -march=x86-64 -mtune=generic -static -nostdlib -ffreestanding -fno-builtin \
  -fno-stack-protector -fno-pie -no-pie -fno-tree-loop-distribute-patterns \
  -fno-asynchronous-unwind-tables -fcf-protection=none -Wall -Wextra -Werror \
  -Wl,--build-id=none -Wl,-z,noexecstack -s \
  -o "$work/sbx-native" "$here/sbx-native.c"
objcopy --remove-section .comment "$work/sbx-native"
cp "$work/sbx-native" "$here/sbx-native"
sha="$(sha256sum "$work/sbx-native" | cut -d' ' -f1)"
size="$(stat -c %s "$work/sbx-native")"
compiler="$(gcc --version | head -1)"
{
  echo "// Generated by bench/native/build.sh from bench/native/sbx-native.c. Do not edit."
  echo "// Compiler: ${compiler}"
  echo
  echo "export const nativeSha256 = \"${sha}\";"
  echo
  echo "export const nativeSize = ${size};"
  echo
  echo "export const nativeCompiler = \"${compiler}\";"
  echo
  printf 'export const nativeBase64 =\n  "%s";\n' "$(base64 -w0 "$work/sbx-native")"
} > "$here/../src/fairness/native-binary.ts"
echo "sbx-native: ${size} bytes, sha256 ${sha}"
