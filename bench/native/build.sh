#!/usr/bin/env bash
# Builds sbx-native.c into two static, libc-free Linux ELFs and regenerates
# bench/src/fairness/native-binary.ts (base64 + SHA-256 of each):
# - x86_64 with gcc, baseline x86-64 (no AVX), so no provider gets a faster code path from wider
#   vectors;
# - aarch64 with clang and lld, baseline armv8-a, for providers on ARM (Upstash runs Graviton).
# Run from anywhere: bash bench/native/build.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "${work:?}"' EXIT
common=(-std=c11 -O2 -static -nostdlib -ffreestanding -fno-builtin -fno-stack-protector -fno-pie
  -fno-asynchronous-unwind-tables -Wall -Wextra -Werror -Wl,--build-id=none -Wl,-z,noexecstack -s)

gcc "${common[@]}" -no-pie -march=x86-64 -mtune=generic -fno-tree-loop-distribute-patterns -fcf-protection=none \
  -o "$work/sbx-native-x86_64" "$here/sbx-native.c"
objcopy --remove-section .comment "$work/sbx-native-x86_64"

clang "${common[@]}" --target=aarch64-linux-gnu -march=armv8-a -fuse-ld=lld \
  -o "$work/sbx-native-aarch64" "$here/sbx-native.c"
llvm-objcopy --remove-section .comment "$work/sbx-native-aarch64" 2>/dev/null ||
  objcopy --remove-section .comment "$work/sbx-native-aarch64" 2>/dev/null || true

cp "$work/sbx-native-x86_64" "$here/sbx-native"
cp "$work/sbx-native-aarch64" "$here/sbx-native-aarch64"
gccv="$(gcc --version | head -1)"
clangv="$(clang --version | head -1)"
out="$here/../src/fairness/native-binary.ts"
{
  echo "// Generated by bench/native/build.sh from bench/native/sbx-native.c. Do not edit."
  echo
  echo "export const nativeBinaries = {"
  for arch in x86_64 aarch64; do
    f="$work/sbx-native-$arch"
    compiler="$gccv"
    [ "$arch" = aarch64 ] && compiler="$clangv"
    echo "  $arch: {"
    echo "    sha256: \"$(sha256sum "$f" | cut -d' ' -f1)\","
    echo "    size: $(stat -c %s "$f"),"
    echo "    compiler: \"${compiler}\","
    printf '    base64:\n      "%s",\n' "$(base64 -w0 "$f")"
    echo "  },"
  done
  echo "} as const;"
} > "$out"
for arch in x86_64 aarch64; do
  echo "sbx-native $arch: $(stat -c %s "$work/sbx-native-$arch") bytes, sha256 $(sha256sum "$work/sbx-native-$arch" | cut -d' ' -f1)"
done
